"""Generate native UI translations from shared/localization/ui.json."""
from pathlib import Path
from collections import Counter
import argparse
import json
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--ios-only', action='store_true', help='Leave Android assets unchanged')
parser.add_argument('--check', action='store_true', help='Validate catalog and generated files without writing')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / 'shared/localization/ui.json').read_text())
languages = ['zh-Hant', 'zh-Hans', 'en']
for key, values in catalog.items():
    if set(values) != set(languages):
        raise SystemExit(f'Incomplete languages: {key}')
    placeholders = Counter(re.findall(r'\{\d+\}', key))
    for language, value in values.items():
        if not isinstance(value, str) or Counter(re.findall(r'\{\d+\}', value)) != placeholders:
            raise SystemExit(f'Invalid placeholders: {language}: {key}')

def output(path, content):
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f'Generated file is out of date: {path.relative_to(root)}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

def quote(value):
    return json.dumps(value, ensure_ascii=False)

for language in languages:
    path = root / 'ios/SydneyBuddy' / f'{language}.lproj/Localizable.strings'
    content = '// Generated by scripts/generate_localizations.py\n' + ''.join(
        quote(key) + ' = ' + quote(values[language]) + ';\n' for key, values in catalog.items()
    )
    output(path, content)
if not args.ios_only:
    output(root / 'android/app/src/main/assets/ui-localizations.json',
           json.dumps(catalog, ensure_ascii=False, indent=2) + '\n')
if args.check:
    print(f'Localization catalog and resources match: {len(catalog)} entries, {len(languages)} languages')
