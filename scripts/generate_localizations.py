"""Generate native UI translations from shared/localization/ui.json."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
catalog=json.loads((root/'shared/localization/ui.json').read_text())
for language in ['zh-Hant','zh-Hans','en']:
    folder=root/'ios/SydneyBuddy'/f'{language}.lproj'
    folder.mkdir(exist_ok=True)
    def quote(value):return json.dumps(value,ensure_ascii=False)
    (folder/'Localizable.strings').write_text('// Generated by scripts/generate_localizations.py\n'+''.join(quote(key)+' = '+quote(values[language])+';\n' for key,values in catalog.items()))
assets=root/'android/app/src/main/assets'
assets.mkdir(parents=True,exist_ok=True)
(assets/'ui-localizations.json').write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+'\n')
